import { useEffect, useState, type ReactNode } from 'react';
import { Outlet, useLocation } from 'react-router-dom';
import { Sidebar } from './Sidebar';
import { Topbar } from './Topbar';
import { cn } from './ui';

function ScrollToTop() {
  const { pathname } = useLocation();
  useEffect(() => {
    window.scrollTo({ top: 0 });
  }, [pathname]);
  return null;
}

export function DashboardLayout() {
  const [drawerOpen, setDrawerOpen] = useState(false);
  const { pathname } = useLocation();

  useEffect(() => {
    const title = NAV_TITLE[pathname] ?? 'Overview';
    document.title = `${title} · SunShift India`;
  }, [pathname]);

  return (
    <div className="min-h-screen">
      <ScrollToTop />
      <Sidebar open={drawerOpen} onClose={() => setDrawerOpen(false)} />
      <div className="lg:pl-[244px]">
        <Topbar onMenu={() => setDrawerOpen(true)} />
        <main key={pathname} className="mx-auto w-full max-w-[1360px] animate-fade-up px-4 py-6 sm:px-6">
          <Outlet />
        </main>
        <footer className="mx-auto w-full max-w-[1360px] px-4 pb-8 pt-2 sm:px-6">
          <p className="text-[11px] leading-relaxed text-faint">
            SunShift India · solar planning estimates generated by the built-in model engine. Values are forecasts and scenarios, not
            meter readings. Connect the SunShift energy engine and Supabase to replace sample data with live figures.
          </p>
        </footer>
      </div>
    </div>
  );
}

const NAV_TITLE: Record<string, string> = {
  '/': 'Overview',
  '/live-energy-flow': 'Live Energy Flow',
  '/digital-twin': 'Energy Digital Twin',
  '/forecast': 'Solar Forecast',
  '/battery': 'Battery',
  '/appliances': 'Appliances',
  '/scenarios': 'Scenarios',
  '/day-ahead-plan': 'Day-ahead Plan',
  '/savings': 'Savings',
  '/run-history': 'Run History',
  '/reports': 'Reports',
  '/rooftop-estimator': 'Rooftop Estimator',
  '/solar-calculator': 'Solar Calculator',
  '/settings': 'Settings',
};

export function PageHeader({
  title,
  subtitle,
  actions,
  className,
}: {
  title: string;
  subtitle?: string;
  actions?: ReactNode;
  className?: string;
}) {
  return (
    <div className={cn('mb-6 flex flex-wrap items-end justify-between gap-4', className)}>
      <div>
        <h1 className="text-[22px] font-bold tracking-tight text-ink">{title}</h1>
        {subtitle ? <p className="mt-1 max-w-2xl text-[13px] leading-relaxed text-muted">{subtitle}</p> : null}
      </div>
      {actions ? <div className="flex flex-wrap items-center gap-2.5">{actions}</div> : null}
    </div>
  );
}
